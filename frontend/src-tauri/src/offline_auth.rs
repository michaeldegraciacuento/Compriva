//! Offline cashier PIN verification (docs/README.md).
//!
//! The terminal caches each cashier's bcrypt PIN hash from the server
//! (GET /api/v1/terminal/cashiers). Verification runs here, in native code,
//! with the same algorithm Laravel uses ($2y$, cost 12).

/// Returns true when `pin` matches `hash`. Malformed hashes never match.
pub fn verify_pin(pin: &str, hash: &str) -> bool {
    if pin.is_empty() || pin.len() > 20 {
        return false;
    }
    bcrypt::verify(pin, hash).unwrap_or(false)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn verifies_laravel_bcrypt_hashes() {
        // Generated by PHP: password_hash("123456", PASSWORD_BCRYPT, ["cost" => 12]).
        let laravel = "$2y$12$ofZelWL3VurjojuwCT27pu/RsvusYdYhJcjmW.nkeVE1nrs5vN0ue";
        assert!(verify_pin("123456", laravel));
        assert!(!verify_pin("123457", laravel));
    }

    #[test]
    fn rejects_empty_oversized_and_malformed_input() {
        let hash = bcrypt::hash("482916", 4).unwrap();
        assert!(!verify_pin("", &hash));
        assert!(!verify_pin(&"9".repeat(21), &hash));
        assert!(!verify_pin("482916", "not-a-hash"));
    }
}
