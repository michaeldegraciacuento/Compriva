namespace App\Domain\Sales\Actions;

use App\Domain\Cashiering\Enums\ShiftStatus;
use App\Domain\Inventory\Services\StockLedger;
use App\Domain\Sales\Enums\SaleStatus;
use App\Domain\Sales\Pricing\FixedPoint;
use App\Domain\Sales\Pricing\TenderCalculator;
use App\Domain\Sales\Services\CartPricer;
use App\Domain\Sales\Services\SupervisorApproval;
use App\Models\CashierShift;
use App\Models\Device;
use App\Models\PaymentMethod;
use App\Models\Sale;
use App\Models\SaleItem;
use App\Models\Store;
use App\Models\User;
use App\Support\Audit\AuditLogger;
use App\Support\Errors\BusinessException;
use App\Support\Errors\ErrorCode;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

/**
 * Checkout: turns a cart into a completed sale in one database transaction.
 *
 * 1. The sale ID is generated by the POS (UUIDv7). Sending the same sale twice
 *    (a retry after a timeout, a double click) returns the first one: a sale is
 *    never recorded twice.
 * 2. The cart is priced again on the server (CartPricer). If the total differs
 *    from what the cashier saw, nothing is saved (TOTAL_MISMATCH).
 * 3. Discounts and price overrides need permission or a manager's approval.
 * 4. Payments are validated (TenderCalculator); only cash gives change.
 * 5. One transaction: receipt number, sale, items with product/tax/cost
 *    snapshots, stock deducted through the StockLedger, discounts, payments.
 *    Any failure (e.g. not enough stock) rolls everything back.
 */
class CompleteSale
{
    public function __construct(
        private readonly CartPricer $pricer,
        private readonly TenderCalculator $tenders,
        private readonly SupervisorApproval $approval,
        private readonly StockLedger $ledger,
        private readonly AuditLogger $audit,
    ) {}

    /**
     * @param  array<string, mixed>  $input  validated CheckoutRequest data
     * @return array{sale: Sale, replayed: bool}
     */
    public function execute(Device $device, User $cashier, array $input): array
    {
        if ($existing = $this->previous($input['id'], $device)) {
            return ['sale' => $existing, 'replayed' => true];
        }

        $shift = CashierShift::where('device_id', $device->id)->where('status', ShiftStatus::Open)->first();
        if ($shift === null || $shift->cashier_id !== $cashier->id) {
            throw new BusinessException('Open your shift on this terminal before selling.', ErrorCode::ShiftRequired, 409);
        }

        $priced = $this->pricer->price($input['lines'], $input['discount'] ?? null);
        $total = $priced['totals']['grand_total'];

        $approver = null;
        foreach ($priced['permissions'] as $permission) {
            $approver = $this->approval->authorize($cashier, $permission, $input['approval'] ?? null, 'This discount or price change');
        }

        if (isset($input['expected_total']) && FixedPoint::cents((string) $input['expected_total']) !== FixedPoint::cents($total)) {
            throw new BusinessException(
                "The total changed to ₱{$total} (prices were updated). Check the cart and take payment again.",
                ErrorCode::TotalMismatch, 409, ['expected' => (string) $input['expected_total'], 'actual' => $total],
            );
        }

        $payments = $this->payments($input['payments'] ?? [], $total);

        try {
            return DB::transaction(fn () => [
                'sale' => $this->record($device, $shift, $cashier, $approver, $input, $priced, $payments),
                'replayed' => false,
            ]);
        } catch (UniqueConstraintViolationException $e) {
            // The same sale arrived twice at the same moment: the other request saved it.
            return ['sale' => $this->previous($input['id'], $device) ?? throw $e, 'replayed' => true];
        }
    }

    private function previous(string $id, Device $device): ?Sale
    {
        $sale = Sale::find($id);
        if ($sale !== null && $sale->device_id !== $device->id) {
            throw new BusinessException('This sale ID was already used on another terminal.', ErrorCode::Conflict, 409);
        }

        return $sale;
    }

    /** @return array{rows: list<array<string, mixed>>, amount_paid: string, change_due: string} */
    private function payments(array $input, string $total): array
    {
        $methods = PaymentMethod::whereIn('code', array_column($input, 'method'))->where('is_active', true)->get()->keyBy('code');

        foreach ($input as $i => $payment) {
            $method = $methods->get($payment['method']);
            if ($method === null) {
                $this->invalid("payments.{$i}.method", 'This payment method is not accepted.');
            }
            if ($method->requires_reference && blank($payment['reference'] ?? null)) {
                $this->invalid("payments.{$i}.reference", "Enter the {$method->name} reference number from the customer's confirmation.");
            }
        }

        $applied = $this->tenders->apply($total, array_map(fn (array $p) => [
            'allows_change' => $methods[$p['method']]->allows_change,
            'tendered' => (string) $p['amount'],
        ], $input));

        $rows = [];
        foreach ($input as $i => $payment) {
            $method = $methods[$payment['method']];
            $rows[] = [
                'payment_method_id' => $method->id,
                'method_code' => $method->code,
                'amount' => $applied['tenders'][$i]['amount'],
                'tendered_amount' => $applied['tenders'][$i]['tendered'],
                'change_amount' => $applied['tenders'][$i]['change'],
                'reference_number' => $method->requires_reference ? trim($payment['reference']) : null,
            ];
        }

        return ['rows' => $rows, 'amount_paid' => $applied['amount_paid'], 'change_due' => $applied['change_due']];
    }

    private function record(Device $device, CashierShift $shift, User $cashier, ?User $approver, array $input, array $priced, array $payments): Sale
    {
        $device = Device::whereKey($device->id)->lockForUpdate()->firstOrFail();
        $sequence = $device->last_receipt_sequence + 1;
        $device->forceFill(['last_receipt_sequence' => $sequence, 'last_seen_at' => now()])->save();

        $store = Store::findOrFail($device->store_id);
        $totals = $priced['totals'];
        $discount = $priced['discount'];
        $now = now();

        $sale = Sale::create([
            'id' => $input['id'],
            'store_id' => $store->id,
            'device_id' => $device->id,
            'cashier_shift_id' => $shift->id,
            'cashier_id' => $cashier->id,
            'receipt_number' => sprintf('%s-%06d', $device->code, $sequence),
            'receipt_sequence' => $sequence,
            'status' => SaleStatus::Completed,
            'customer_name' => $input['customer_name'] ?? null,
            'customer_id_number' => $discount['customer_id_number'] ?? null,
            'gross_amount' => $totals['gross_amount'],
            'discount_total' => $totals['discount_total'],
            'vatable_sales' => $totals['vatable_sales'],
            'vat_amount' => $totals['vat_amount'],
            'vat_exempt_sales' => $totals['vat_exempt_sales'],
            'zero_rated_sales' => $totals['zero_rated_sales'],
            'rounding_adjustment' => '0',
            'grand_total' => $totals['grand_total'],
            'amount_paid' => $payments['amount_paid'],
            'change_due' => $payments['change_due'],
            'occurred_at' => $now,
            'business_date' => $now->copy()->setTimezone($store->timezone)->toDateString(),
            'synced_at' => $now,
            'operation_id' => $input['id'],
            'notes' => $input['notes'] ?? null,
        ]);

        foreach ($priced['lines'] as $i => $line) {
            $item = $this->item($sale, $i + 1, $line, $cashier, $approver);

            if ($line['discount'] !== null) {
                $sale->discounts()->create([
                    'sale_item_id' => $item->id,
                    'name' => 'Item discount',
                    'kind' => 'manual',
                    'type' => $line['discount']['type'],
                    'value' => $line['discount']['value'],
                    'amount' => $line['amounts']['item_discount'],
                    'approved_by' => $approver?->id,
                    'created_at' => $now,
                ]);
            }
        }

        if ($discount !== null) {
            $amount = FixedPoint::format(array_sum(array_map(fn ($l) => FixedPoint::cents($l['amounts']['sale_discount']), $priced['lines'])));
            $sale->discounts()->create([
                'discount_id' => $discount['discount_id'],
                'name' => $discount['name'],
                'kind' => $discount['kind'],
                'type' => $discount['type'],
                'value' => $discount['value'],
                'amount' => $amount,
                'customer_id_number' => $discount['customer_id_number'],
                'approved_by' => $discount['needs_permission'] ? $approver?->id : null,
                'created_at' => $now,
            ]);
        }

        foreach ($payments['rows'] as $payment) {
            $sale->payments()->create($payment + ['paid_at' => $now, 'created_at' => $now]);
        }

        $this->audit->record('sale.completed', $sale, new: [
            'receipt_number' => $sale->receipt_number, 'grand_total' => $sale->grand_total, 'lines' => count($priced['lines']),
            'approved_by' => $approver?->id !== $cashier->id ? $approver?->id : null,
        ], device: $device);

        return $sale;
    }

    private function item(Sale $sale, int $number, array $line, User $cashier, ?User $approver): SaleItem
    {
        $id = (string) Str::uuid7();
        $stock = $this->ledger->sell($sale, $id, $line['sku'], $line['base_quantity'], $cashier);
        $amounts = $line['amounts'];

        return SaleItem::create([
            'id' => $id,
            'sale_id' => $sale->id,
            'line_number' => $number,
            'product_sku_id' => $line['sku']->id,
            'unit_id' => $line['unit']->id,
            'stock_batch_id' => $stock['batch_id'],
            'product_name' => $line['sku']->name,
            'sku_code' => $line['sku']->code,
            'barcode' => $line['barcode'],
            'unit_name' => $line['unit']->name,
            'conversion_factor' => $line['factor'],
            'quantity' => $line['quantity'],
            'base_quantity' => $line['base_quantity'],
            'regular_unit_price' => $line['regular_unit_price'],
            'unit_price' => $line['unit_price'],
            'price_override_by' => $line['price_overridden'] ? $approver?->id : null,
            'unit_cost' => bcmul($stock['unit_cost'], $line['factor'], 4),
            'gross_amount' => $amounts['gross'],
            'discount_amount' => $amounts['discount'],
            'tax_rate_id' => $line['tax']['id'],
            'tax_code' => $line['tax']['code'],
            'tax_type' => $amounts['vat_exempted'] ? 'vat_exempt' : $line['tax']['type'],
            'tax_rate' => $amounts['vat_exempted'] ? '0' : $line['tax']['rate'],
            'taxable_amount' => $amounts['taxable'],
            'tax_amount' => $amounts['tax'],
            'line_total' => $amounts['total'],
            'created_at' => $sale->occurred_at,
        ]);
    }

    private function invalid(string $field, string $message): never
    {
        throw new BusinessException($message, ErrorCode::ValidationFailed, 422, ['fields' => [$field => [$message]]]);
    }
}
