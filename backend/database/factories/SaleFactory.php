<?php

namespace Database\Factories;

use App\Domain\Cashiering\Enums\ShiftStatus;
use App\Models\CashierShift;
use App\Models\Device;
use App\Models\Sale;
use Illuminate\Database\Eloquent\Factories\Factory;
use Illuminate\Support\Str;

/**
 * A completed cash sale with consistent VAT-inclusive totals. Reuses the
 * terminal's open shift and continues its receipt sequence.
 *
 * Totals are not derived from items: summing lines is the Sales domain's job.
 *
 * @extends Factory<Sale>
 */
class SaleFactory extends Factory
{
    public function definition(): array
    {
        $total = number_format(fake()->numberBetween(50, 5000), 4, '.', '');
        $vat = bcdiv(bcmul($total, '12', 8), '112', 4);

        return [
            'id' => (string) Str::uuid7(),                  // generated by the terminal in production
            'device_id' => Device::factory()->active(),
            'store_id' => fn (array $a) => Device::find($a['device_id'])->store_id,
            'cashier_shift_id' => fn (array $a) => CashierShift::where('device_id', $a['device_id'])
                ->where('status', ShiftStatus::Open)->value('id')
                ?? CashierShift::factory()->create(['device_id' => $a['device_id']])->id,
            'cashier_id' => fn (array $a) => CashierShift::find($a['cashier_shift_id'])->cashier_id,
            'receipt_sequence' => fn (array $a) => (int) Sale::where('device_id', $a['device_id'])->max('receipt_sequence') + 1,
            'receipt_number' => fn (array $a) => sprintf('%s-%06d', Device::find($a['device_id'])->code, $a['receipt_sequence']),
            'status' => 'completed',
            'gross_amount' => $total,
            'vatable_sales' => bcsub($total, $vat, 4),
            'vat_amount' => $vat,
            'grand_total' => $total,
            'amount_paid' => $total,
            'occurred_at' => now(),
            'business_date' => now('Asia/Manila')->toDateString(),
            'synced_at' => now(),
            'operation_id' => (string) Str::uuid7(),
        ];
    }
}
